////*****************////
////*****清屏函数****////
////*****************////
void clear_screen(uchar m)
{
 uchar i,j;
 write_command(0x40);        //设置起始行
 for(i=0;i<8;i++)
  {
  write_command(i|0xb0);     //设置起始页
  write_command(0x10);       //设置列的高八位
  write_command(0x00);       //设置列的低八位
  for(j=0;j<128;j++)
   {
    write_data(m);           //设置清屏方式
   }
  }
}
