//在指定位置显示一个字符串//
////*****************////
void disp_str(uchar col,uchar pag,uchar *cn)
{
   while(*cn!=0)
  {
    if(col==128)
    {
      pag+=2;
      col=0;
    }
    if(pag==8)
    {
      pag=0;
    }
    disp_word(col,pag,*cn++);
    col+=8;
  }
}


