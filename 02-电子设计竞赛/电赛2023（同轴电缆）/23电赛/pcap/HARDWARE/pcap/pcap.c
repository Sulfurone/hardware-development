 //MCU IN SPI1
u8 SPI_Read_Bit(void)
{	 																
     u8 Read_Bit;
	   Read_Bit = GPIO_ReadInputDataBit(GPIOA,GPIO_Pin_6); 
	   return Read_Bit;
}

//在SCK下降沿写入一个BIT
void SPI_Send_Bit(u8 bbit)					    
{
//       SPI_Enable();
	   SPI_SCLK_High;
	   __3nop();
	   if(bbit == 1)
	   {
	          SPI_MOSI_High;
		 }
	   else	if(bbit == 0)
	   {
	          SPI_MOSI_Low;
		 }
	   __3nop();
	   SPI_SCLK_Low;
	   __3nop();
}

 //最高字节为0  SPI1
u32 spi_read(void)    
{
       u8 cnt;
       u32 rbuf32=0x00000000;
       for(cnt=24;cnt>0;cnt--)
       {
              SPI_SCLK_High; 
              __3nop();
              rbuf32<<=1;
              if(SPI_Read_Bit() == 1)
                    rbuf32 |=1;
              SPI_SCLK_Low; 
              __3nop();
        }
       return(rbuf32);
}

//写入一个8位数据
void write_date_8(u8 date)
{
       u8 cnt = 0;
       __3nop();
       SPI_Enable();
       __3nop();
			 __3nop();
       for(cnt=8;cnt>0;cnt--)
       {
              if((date&0x80)==0x80)
                     SPI_Send_Bit(1);
              else
                     SPI_Send_Bit(0);    
              date = date<<1;
        }
       __3nop();
       __3nop();
}


//写入一个16位数据
void write_date_16(u16 date)
{
       u8 cnt = 0;
       __3nop();
       SPI_Enable();
       __3nop();
	     __3nop();
       for(cnt=16;cnt>0;cnt--)
       {
              if((date&0x8000)==0x8000)
                     SPI_Send_Bit(1);
              else
                     SPI_Send_Bit(0);
              date = date<<1;
        }
       __3nop();
       __3nop();
}


//写入一个32位的数据
void write_date_32(u32 date)
{
       u8 cnt;
       __3nop();
       SPI_Enable();
       __3nop();
			 __3nop();
       for(cnt=32;cnt>0;cnt--)
       {
              if((date&0x80000000)==0x80000000)
                     SPI_Send_Bit(1);
              else
                     SPI_Send_Bit(0);
              date = date<<1;
        }
       __3nop(); 
       __3nop();
}

void spi_test(void)
{
        u8 i;
        u8 tmp = 0x80;
        const u16 test_reg  =  0x0005;     //测试SRAM地址
        /*const*/ u8 test_data  =  0xA5;   //测试数据
        u8 test_read = 0x00;

        while(test_data!=test_read)
        {
                //操作码9005A5H表示向SRAM写入数据A5H
                SPI_Disable();
                __3nop();
								__3nop();
                write_date_16(test_reg|0x9000);//9005H 
                write_date_8(test_data);//A5H
                __3nop();
					
                //操作码1005XXH表示从SRAM读取XXH
                tmp = 0x80;
                SPI_Disable();
                __3nop();
								__3nop();
                write_date_16(test_reg|0x1000);//1005H
                test_read=0x00;
                for(i=8;i>0;i--)
                {
                       SPI_SCLK_High;
                       __3nop();
                       if(SPI_Read_Bit() == 1)
                       {
                              test_read |=tmp;
                              __3nop();
                              __3nop();
                        }  
                       tmp /=2;
                       SPI_SCLK_Low;
                       __3nop();
                 }
         }  
}

