/**
  * @brief  Set the high-side (TIM1_CH1) duty cycle.
  * @note   TIM1_CH1N is driven by the advanced timer as the hardware
  *         complementary output, so it always has the inverse state.
  */
void PWM_SetDutyPermille(uint16_t duty_permille)
{
  uint32_t compare;

  if (duty_permille > PWM_DUTY_PERMILLE_MAX)
  {
    duty_permille = PWM_DUTY_PERMILLE_MAX;
  }

  /* CCR may be ARR + 1 for a continuous 100% active output. */
  compare = ((PWM_PERIOD_TICKS * duty_permille) +
             (PWM_DUTY_PERMILLE_MAX / 2U)) / PWM_DUTY_PERMILLE_MAX;
  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, compare);
}

